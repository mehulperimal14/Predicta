"""
PREDICTA – Alert System
Multi-channel alert delivery: Email, Telegram, SMS, Dashboard WebSocket
"""

import smtplib
import requests
import threading
from datetime import datetime, timedelta
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from flask import current_app
from database import db
from models import AlertHistory

# Cooldown to prevent alert flooding (per device+fault type)
_alert_cooldown = {}
COOLDOWN_MINUTES = 15


def _is_in_cooldown(device_id: str, fault_type: str) -> bool:
    key = f"{device_id}:{fault_type}"
    if key in _alert_cooldown:
        if datetime.utcnow() < _alert_cooldown[key]:
            return True
    _alert_cooldown[key] = datetime.utcnow() + timedelta(minutes=COOLDOWN_MINUTES)
    return False


def send_alert(device_id: str, fault_type: str, severity: str,
               message: str, prediction: dict = None):
    """
    Main alert dispatcher. Sends email + Telegram based on severity.
    Runs in background thread to not block API response.
    """
    if _is_in_cooldown(device_id, fault_type):
        return

    def _dispatch():
        with current_app.app_context():
            config = current_app.config

            if severity in ("HIGH", "CRITICAL"):
                _send_email(device_id, fault_type, severity, message, prediction, config)
                _send_telegram(device_id, fault_type, severity, message, prediction, config)

            elif severity == "MEDIUM":
                _send_email(device_id, fault_type, severity, message, prediction, config)

            # Log to DB
            _log_alert(device_id, "MULTI", message, severity)

    thread = threading.Thread(target=_dispatch, daemon=True)
    thread.start()


def _send_email(device_id, fault_type, severity, message, prediction, config):
    """Send HTML email alert via SMTP."""
    try:
        rul = prediction.get("rul_days", "N/A") if prediction else "N/A"
        confidence = prediction.get("confidence", "N/A") if prediction else "N/A"
        recommendation = prediction.get("recommendation", "") if prediction else ""

        html_body = f"""
        <html><body style="font-family:Arial,sans-serif;background:#0f1117;color:#e0e0e0;padding:20px;">
        <div style="max-width:600px;margin:auto;background:#1a1d2e;border-radius:12px;padding:24px;
                    border-left:5px solid {'#ff4444' if severity=='CRITICAL' else '#ff8c00' if severity=='HIGH' else '#ffd700'};">
          <h2 style="color:{'#ff4444' if severity=='CRITICAL' else '#ff8c00'};margin:0 0 16px 0;">
            ⚠️ PREDICTA ALERT – {severity}
          </h2>
          <table style="width:100%;border-collapse:collapse;">
            <tr><td style="padding:8px;color:#aaa;">Device</td>
                <td style="padding:8px;font-weight:bold;color:#00d4ff;">{device_id}</td></tr>
            <tr style="background:#12151e;"><td style="padding:8px;color:#aaa;">Fault Type</td>
                <td style="padding:8px;color:#ff6b35;">{fault_type}</td></tr>
            <tr><td style="padding:8px;color:#aaa;">Severity</td>
                <td style="padding:8px;font-weight:bold;color:{'#ff4444' if severity=='CRITICAL' else '#ff8c00'};">{severity}</td></tr>
            <tr style="background:#12151e;"><td style="padding:8px;color:#aaa;">ML Confidence</td>
                <td style="padding:8px;">{confidence}%</td></tr>
            <tr><td style="padding:8px;color:#aaa;">Est. RUL</td>
                <td style="padding:8px;">{rul} days</td></tr>
            <tr style="background:#12151e;"><td style="padding:8px;color:#aaa;">Timestamp</td>
                <td style="padding:8px;">{datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')} UTC</td></tr>
          </table>
          <div style="margin-top:16px;padding:12px;background:#0d1117;border-radius:8px;">
            <p style="color:#00d4ff;margin:0 0 8px 0;font-weight:bold;">📋 Details</p>
            <p style="margin:0;color:#ccc;">{message}</p>
          </div>
          {'<div style="margin-top:16px;padding:12px;background:#0d2a1a;border-radius:8px;"><p style="color:#00ff88;margin:0 0 8px 0;font-weight:bold;">🔧 Recommended Action</p><p style="margin:0;color:#ccc;">' + recommendation + '</p></div>' if recommendation else ''}
          <p style="margin-top:20px;color:#666;font-size:12px;">
            This alert was generated by PREDICTA AI-Based Predictive Maintenance System.<br>
            Please log in to the dashboard for full analysis: <a href="http://localhost:5000" style="color:#00d4ff;">predicta.local</a>
          </p>
        </div>
        </body></html>
        """

        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"[PREDICTA {severity}] {fault_type} – Device {device_id}"
        msg["From"]    = config["ALERT_FROM"]
        msg["To"]      = ", ".join(config["ALERT_EMAILS"])
        msg.attach(MIMEText(html_body, "html"))

        with smtplib.SMTP(config["SMTP_SERVER"], config["SMTP_PORT"]) as smtp:
            smtp.ehlo()
            smtp.starttls()
            smtp.login(config["SMTP_USERNAME"], config["SMTP_PASSWORD"])
            smtp.send_message(msg)

        print(f"[ALERT] Email sent: {fault_type} | {severity}")
        _log_alert(device_id, "EMAIL", message, severity, delivered=True,
                   recipient=", ".join(config["ALERT_EMAILS"]))

    except Exception as e:
        print(f"[ALERT] Email error: {e}")
        _log_alert(device_id, "EMAIL", f"FAILED: {e}", severity)


def _send_telegram(device_id, fault_type, severity, message, prediction, config):
    """Send Telegram bot message."""
    bot_token = config.get("TELEGRAM_BOT_TOKEN", "")
    chat_id   = config.get("TELEGRAM_CHAT_ID", "")

    if not bot_token or not chat_id:
        return

    try:
        rul = prediction.get("rul_days", "N/A") if prediction else "N/A"
        emoji = "🔴" if severity == "CRITICAL" else "🟠" if severity == "HIGH" else "🟡"

        text = (
            f"{emoji} *PREDICTA ALERT – {severity}*\n\n"
            f"🏭 *Device:* `{device_id}`\n"
            f"⚡ *Fault:* {fault_type}\n"
            f"📊 *Severity:* {severity}\n"
            f"⏱ *Est. RUL:* {rul} days\n"
            f"🕐 *Time:* {datetime.utcnow().strftime('%Y-%m-%d %H:%M')} UTC\n\n"
            f"📋 *Details:* {message}\n\n"
            f"🔗 Dashboard: http://predicta.local"
        )

        url = f"https://api.telegram.org/bot{bot_token}/sendMessage"
        resp = requests.post(url, json={
            "chat_id": chat_id,
            "text": text,
            "parse_mode": "Markdown"
        }, timeout=10)

        if resp.status_code == 200:
            print(f"[ALERT] Telegram sent: {fault_type}")
            _log_alert(device_id, "TELEGRAM", message, severity, delivered=True, recipient=chat_id)
        else:
            print(f"[ALERT] Telegram error: {resp.text}")

    except Exception as e:
        print(f"[ALERT] Telegram exception: {e}")


def _log_alert(device_id, alert_type, message, severity,
               delivered=False, recipient=""):
    """Log alert to database."""
    try:
        log = AlertHistory(
            device_id=device_id,
            alert_type=alert_type,
            message=message[:500],
            severity=severity,
            delivered=delivered,
            recipient=recipient[:200]
        )
        db.session.add(log)
        db.session.commit()
    except Exception as e:
        print(f"[ALERT] DB log error: {e}")
        db.session.rollback()
